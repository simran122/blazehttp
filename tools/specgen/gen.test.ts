import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { checkDrift, generate } from './gen.ts';
import { parseSpec, type Spec } from './spec-types.ts';

const loadJson = (path: string): unknown => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const mini = parseSpec(loadJson('./fixtures/mini-spec.json'));
const withErrors = (errors: Spec['errors']): Spec => ({ ...mini, errors });

describe('generate', () => {
  it('generates TS and Rust for the mini fixture', () => {
    const { ts, rust } = generate(mini);
    expect(ts).toMatchInlineSnapshot(`
      "// Generated by tools/specgen/gen.ts from policy/spec.json. Do not edit; run pnpm specgen.

      export type HttpErrorCode =
        | 'TIMEOUT'
        | 'HTTP_STATUS'
        | 'QUEUE_FULL';

      export interface ErrorDetailMap {
        TIMEOUT: 'connect' | 'slow-body';
        HTTP_STATUS: { status: number };
        QUEUE_FULL: { scope: 'client' | 'global'; bound: number };
      }

      /** Index = wire code id. \`details\` are the ordered values behind the wire detail id (detail list or enum field). */
      export const ERROR_WIRE: readonly {
        code: HttpErrorCode;
        details: readonly string[] | undefined;
        fields: readonly string[] | undefined;
      }[] = [
        { code: 'TIMEOUT', details: ['connect', 'slow-body'], fields: undefined },
        { code: 'HTTP_STATUS', details: undefined, fields: ['status'] },
        { code: 'QUEUE_FULL', details: ['client', 'global'], fields: ['scope', 'bound'] },
      ];

      const ERROR_FORMAT: { readonly [C in HttpErrorCode]: (detail: ErrorDetailMap[C]) => string } = {
        TIMEOUT: (detail) => \`TIMEOUT/\${detail}\`,
        HTTP_STATUS: () => 'HTTP_STATUS',
        QUEUE_FULL: (detail) => \`QUEUE_FULL/\${detail.scope}\`,
      };

      /** Display form of a code and its detail, e.g. \`PROTOCOL/malformed-response\`. */
      export function formatErrorCode<C extends HttpErrorCode>(code: C, detail: ErrorDetailMap[C]): string {
        return ERROR_FORMAT[code](detail);
      }

      export const H1_LIMITS = {
        maxHeadBytes: 65536,
      } as const;

      export type Method = 'GET' | 'POST';
      "
    `);
    expect(rust).toMatchInlineSnapshot(`
      "// Generated by tools/specgen/gen.ts from policy/spec.json. Do not edit; run pnpm specgen.

      #[derive(Clone, Copy, Debug, PartialEq, Eq)]
      pub enum TimeoutDetail {
          Connect,
          SlowBody,
      }

      impl TimeoutDetail {
          #[must_use]
          pub fn to_wire(self) -> u32 {
              match self {
                  Self::Connect => 0,
                  Self::SlowBody => 1,
              }
          }

          #[must_use]
          pub fn from_wire(id: u32) -> Option<Self> {
              match id {
                  0 => Some(Self::Connect),
                  1 => Some(Self::SlowBody),
                  _ => None,
              }
          }

          #[must_use]
          pub fn as_str(self) -> &'static str {
              match self {
                  Self::Connect => "connect",
                  Self::SlowBody => "slow-body",
              }
          }
      }

      #[derive(Clone, Copy, Debug, PartialEq, Eq)]
      pub enum QueueScope {
          Client,
          Global,
      }

      impl QueueScope {
          #[must_use]
          pub fn to_wire(self) -> u32 {
              match self {
                  Self::Client => 0,
                  Self::Global => 1,
              }
          }

          #[must_use]
          pub fn from_wire(id: u32) -> Option<Self> {
              match id {
                  0 => Some(Self::Client),
                  1 => Some(Self::Global),
                  _ => None,
              }
          }

          #[must_use]
          pub fn as_str(self) -> &'static str {
              match self {
                  Self::Client => "client",
                  Self::Global => "global",
              }
          }
      }
      #[derive(Clone, Copy, Debug, PartialEq, Eq)]
      pub enum Method {
          Get,
          Post,
      }

      impl Method {
          #[must_use]
          pub fn to_wire(self) -> u32 {
              match self {
                  Self::Get => 0,
                  Self::Post => 1,
              }
          }

          #[must_use]
          pub fn from_wire(id: u32) -> Option<Self> {
              match id {
                  0 => Some(Self::Get),
                  1 => Some(Self::Post),
                  _ => None,
              }
          }

          #[must_use]
          pub fn as_str(self) -> &'static str {
              match self {
                  Self::Get => "GET",
                  Self::Post => "POST",
              }
          }
      }

      #[derive(Clone, Copy, Debug, PartialEq, Eq)]
      pub enum ErrorCode {
          Timeout(TimeoutDetail),
          QueueFull { scope: QueueScope, bound: u32 },
      }

      const fn pack(code: u32, detail: u32) -> u32 {
          code | (detail << 8)
      }

      impl ErrorCode {
          pub const ALL_SAMPLES: &[Self] = &[
              Self::Timeout(TimeoutDetail::Connect),
              Self::Timeout(TimeoutDetail::SlowBody),
              Self::QueueFull {
                  scope: QueueScope::Client,
                  bound: 7,
              },
              Self::QueueFull {
                  scope: QueueScope::Global,
                  bound: 7,
              },
          ];

          /// Wire word 1 is \`code_id | detail_id << 8\`; word 2 is the numeric field.
          #[must_use]
          pub fn to_wire(self) -> (u32, u32) {
              match self {
                  Self::Timeout(detail) => (pack(0, detail.to_wire()), 0),
                  Self::QueueFull { scope, bound } => (pack(2, scope.to_wire()), bound),
              }
          }

          #[must_use]
          pub fn from_wire(code: u32, arg: u32) -> Option<Self> {
              let detail = code >> 8;
              match code & 0xFF {
                  0 => TimeoutDetail::from_wire(detail).map(Self::Timeout),
                  2 => QueueScope::from_wire(detail).map(|scope| Self::QueueFull { scope, bound: arg }),
                  _ => None,
              }
          }
      }

      impl core::fmt::Display for ErrorCode {
          fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
              match self {
                  Self::Timeout(detail) => write!(f, "TIMEOUT/{}", detail.as_str()),
                  Self::QueueFull { scope, .. } => write!(f, "QUEUE_FULL/{}", scope.as_str()),
              }
          }
      }

      #[derive(Clone, Copy, Debug, PartialEq, Eq)]
      pub struct H1Limits {
          pub max_head_bytes: usize,
      }

      pub const H1_LIMITS: H1Limits = H1Limits {
          max_head_bytes: 65_536,
      };
      "
    `);
  });

  it('generates the real spec with all 15 codes in order', () => {
    const real = parseSpec(loadJson('../../policy/spec.json'));
    expect(real.errors).toHaveLength(15);
    expect(generate(real).ts).toContain('export type HttpErrorCode =');
  });

  it('rejects string fields on wire codes', () => {
    expect(() => generate(withErrors([{ code: 'SSRF_BLOCKED', fields: { address: 'string' } }]))).toThrow(
      /wire: false/,
    );
  });

  it('rejects duplicate codes and empty detail lists', () => {
    const a = { code: 'TIMEOUT', details: ['connect'] };
    expect(() => generate(withErrors([a, a]))).toThrow(/duplicate code/);
    expect(() => generate(withErrors([{ code: 'TIMEOUT', details: [] }]))).toThrow(/empty/);
  });

  it('rejects malformed shapes', () => {
    const bad: Spec['errors'][number][] = [
      { code: 'lower', details: ['a'] },
      { code: 'A' },
      { code: 'A', details: ['a'], fields: { n: 'u32' } },
      { code: 'A', details: ['a', 'a'] },
      { code: 'A', details: ['a-b', 'a/b'] },
      { code: 'A', fields: {} },
      { code: 'A', fields: { x: [] } },
      { code: 'A', fields: { x: 'u32', y: 'u32' } },
      { code: 'A', fields: { x: ['a'], y: ['b'] } },
    ];
    for (const e of bad) expect(() => generate(withErrors([e])), e.code).toThrow();
    const many = Array.from({ length: 257 }, (_, i) => ({ code: `C${'A'.repeat(i + 1)}`, details: ['a'] }));
    expect(() => generate(withErrors(many))).toThrow(/256/);
  });

  it('rejects bad methods and limits', () => {
    expect(() => generate({ ...mini, methods: [] })).toThrow(/methods/);
    expect(() => generate({ ...mini, methods: ['CONNECT'] })).toThrow(/CONNECT/);
    expect(() => generate({ ...mini, methods: ['GET', 'GET'] })).toThrow(/duplicate/);
    expect(() => generate({ ...mini, limits: { h1: { maxHeadBytes: -1 } } })).toThrow(/limits/);
    expect(() => generate({ ...mini, limits: { h1: { max_head: 1 } } })).toThrow(/limits/);
  });
});

describe('parseSpec', () => {
  const base = loadJson('./fixtures/mini-spec.json') as Record<string, unknown>;
  const rejects = (raw: unknown, path: RegExp): void => {
    expect(() => parseSpec(raw)).toThrow(path);
  };

  it('names the JSON path of the first structural error', () => {
    rejects(null, /\$: expected an object/);
    rejects({ ...base, errors: 1 }, /\$\.errors: expected an array/);
    rejects({ ...base, errors: [{ code: 1 }] }, /\$\.errors\[0\]\.code: expected a string/);
    rejects({ ...base, errors: [{ code: 'A', wire: 'no' }] }, /\$\.errors\[0\]\.wire: expected a boolean/);
    rejects({ ...base, errors: [{ code: 'A', wires: false }] }, /\$\.errors\[0\]\.wires: unknown key/);
    rejects({ ...base, errors: [{ code: 'A', details: [1] }] }, /\$\.errors\[0\]\.details\[0\]/);
    rejects({ ...base, errors: [{ code: 'A', fields: { x: 'f64' } }] }, /\$\.errors\[0\]\.fields\.x/);
    rejects({ ...base, limits: { h1: { a: 'x' } } }, /\$\.limits\.h1\.a: expected a number/);
    rejects({ ...base, methods: [1] }, /\$\.methods\[0\]/);
  });

  it('accepts optional enumType', () => {
    expect(parseSpec(base).errors[2]?.enumType).toBe('QueueScope');
  });
});

describe('checkDrift', () => {
  it('reports drift', () => {
    const files = [
      { path: 'a.ts', content: 'one' },
      { path: 'b.rs', content: 'two' },
    ];
    const committed: Record<string, string> = { 'a.ts': 'one', 'b.rs': 'two' };
    expect(checkDrift(files, (p) => committed[p])).toEqual({ ok: true });
    committed['b.rs'] = 'modified';
    expect(checkDrift(files, (p) => committed[p])).toEqual({ ok: false, file: 'b.rs' });
    expect(checkDrift(files, () => undefined)).toEqual({ ok: false, file: 'a.ts' });
  });
});
