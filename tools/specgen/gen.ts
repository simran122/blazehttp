import { readFileSync, writeFileSync } from 'node:fs';
import { type ErrorSpec, type FieldType, pascal, parseSpec, type Spec, validateSpec } from './spec-types.ts';

const TS_OUT = 'packages/blazehttp/src/generated/spec.ts';
const RUST_OUT = 'crates/engine-core/src/generated/spec.rs';
const HEADER = 'Generated by tools/specgen/gen.ts from policy/spec.json. Do not edit; run pnpm specgen.';
/** Sample numeric field value used by `ErrorCode::ALL_SAMPLES`. */
const SAMPLE_NUMBER = 7;
/** rustfmt breaks single-line struct literals and patterns above this body width. */
const RUST_LITERAL_WIDTH = 18;

/** One wire code, normalised: the enum behind its detail id and the optional numeric word. */
interface WireCode {
  readonly id: number;
  readonly code: string;
  readonly variant: string;
  readonly values: readonly string[] | undefined;
  readonly valueType: string;
  /** Set when values come from an enum field; `undefined` for plain detail codes. */
  readonly enumField: string | undefined;
  readonly numberField: string | undefined;
}

const q = (s: string): string => `'${s}'`;
const snake = (s: string): string => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const variantOf = (code: string): string => pascal(code.toLowerCase());
const isEnum = (t: FieldType): t is readonly string[] => typeof t !== 'string';

const toWireCode = (e: ErrorSpec, id: number): WireCode => {
  const variant = variantOf(e.code);
  const fields = Object.entries(e.fields ?? {});
  const enumEntry = fields.find(([, t]) => isEnum(t));
  const numberEntry = fields.find(([, t]) => t === 'u32');
  const enumValues = enumEntry?.[1];
  return {
    id,
    code: e.code,
    variant,
    values: e.details ?? (enumValues !== undefined && isEnum(enumValues) ? enumValues : undefined),
    valueType: e.details ? `${variant}Detail` : (e.enumType ?? `${variant}${pascal(enumEntry?.[0] ?? '')}`),
    enumField: enumEntry?.[0],
    numberField: numberEntry?.[0],
  };
};

const wireCodes = (spec: Spec): WireCode[] =>
  spec.errors.flatMap((e, id) => (e.wire === false ? [] : [toWireCode(e, id)]));

const tsFieldType = (t: FieldType): string => (isEnum(t) ? t.map(q).join(' | ') : t === 'u32' ? 'number' : 'string');

const tsDetail = (e: ErrorSpec): string =>
  e.details
    ? e.details.map(q).join(' | ')
    : `{ ${Object.entries(e.fields ?? {})
        .map(([name, t]) => `${name}: ${tsFieldType(t)}`)
        .join('; ')} }`;

/** Display form: `CODE/detail` for detail codes and enum fields, bare `CODE` otherwise. */
const tsFormatter = (e: ErrorSpec): string => {
  const enumField = Object.entries(e.fields ?? {}).find(([, t]) => isEnum(t))?.[0];
  if (e.details) return `(detail) => \`${e.code}/\${detail}\``;
  if (enumField !== undefined) return `(detail) => \`${e.code}/\${detail.${enumField}}\``;
  return `() => ${q(e.code)}`;
};

const tsWireEntry = (e: ErrorSpec): string => {
  const enumValues = Object.values(e.fields ?? {}).find(isEnum);
  const details = e.details ?? enumValues;
  const list = (v: readonly string[] | undefined): string => (v ? `[${v.map(q).join(', ')}]` : 'undefined');
  const fields = e.fields ? Object.keys(e.fields) : undefined;
  return `  { code: ${q(e.code)}, details: ${list(details)}, fields: ${list(fields)} },`;
};

const generateTs = (spec: Spec): string =>
  [
    `// ${HEADER}`,
    '',
    'export type HttpErrorCode =',
    ...spec.errors.map((e, i) => `  | ${q(e.code)}${i === spec.errors.length - 1 ? ';' : ''}`),
    '',
    'export interface ErrorDetailMap {',
    ...spec.errors.map((e) => `  ${e.code}: ${tsDetail(e)};`),
    '}',
    '',
    '/** Index = wire code id. `details` are the ordered values behind the wire detail id (detail list or enum field). */',
    'export const ERROR_WIRE: readonly {',
    '  code: HttpErrorCode;',
    '  details: readonly string[] | undefined;',
    '  fields: readonly string[] | undefined;',
    '}[] = [',
    ...spec.errors.map(tsWireEntry),
    '];',
    '',
    'const ERROR_FORMAT: { readonly [C in HttpErrorCode]: (detail: ErrorDetailMap[C]) => string } = {',
    ...spec.errors.map((e) => `  ${e.code}: ${tsFormatter(e)},`),
    '};',
    '',
    '/** Display form of a code and its detail, e.g. `PROTOCOL/malformed-response`. */',
    'export function formatErrorCode<C extends HttpErrorCode>(code: C, detail: ErrorDetailMap[C]): string {',
    '  return ERROR_FORMAT[code](detail);',
    '}',
    '',
    'export const H1_LIMITS = {',
    ...Object.entries(spec.limits.h1).map(([k, v]) => `  ${k}: ${String(v)},`),
    '} as const;',
    '',
    `export type Method = ${spec.methods.map(q).join(' | ')};`,
    '',
  ].join('\n');

/** Groups digits by thousands from five digits up, as clippy's unreadable_literal lint expects. */
const rustNumber = (n: number): string => (n >= 10_000 ? n.toLocaleString('en-US').replaceAll(',', '_') : String(n));

/** Struct literal or pattern as rustfmt prints it: one line while the body is short, else one field per line. */
const rustBraces = (head: string, parts: readonly string[], indent: number, width: number): string => {
  const body = parts.join(', ');
  if (body.length <= width) return `${head} { ${body} }`;
  const pad = ' '.repeat(indent + 4);
  return `${head} {\n${parts.map((p) => `${pad}${p},`).join('\n')}\n${' '.repeat(indent)}}`;
};

/** Fieldless enum with wire ids, string forms and fallible decoding. */
const rustEnum = (name: string, values: readonly string[], ident: (value: string) => string): string => {
  const arms = (f: (value: string, id: number) => string): string =>
    values.map((v, id) => `            ${f(v, id)},`).join('\n');
  return `#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ${name} {
${values.map((v) => `    ${ident(v)},`).join('\n')}
}

impl ${name} {
    #[must_use]
    pub fn to_wire(self) -> u32 {
        match self {
${arms((v, id) => `Self::${ident(v)} => ${String(id)}`)}
        }
    }

    #[must_use]
    pub fn from_wire(id: u32) -> Option<Self> {
        match id {
${arms((v, id) => `${String(id)} => Some(Self::${ident(v)})`)}
            _ => None,
        }
    }

    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
${arms((v) => `Self::${ident(v)} => "${v}"`)}
        }
    }
}
`;
};

const rustVariant = (c: WireCode): string => {
  if (c.enumField === undefined && c.numberField === undefined) return `    ${c.variant}(${c.valueType}),`;
  const parts = [
    ...(c.enumField === undefined ? [] : [`${snake(c.enumField)}: ${c.valueType}`]),
    ...(c.numberField === undefined ? [] : [`${snake(c.numberField)}: u32`]),
  ];
  return `    ${rustBraces(c.variant, parts, 4, 35)},`;
};

/** Pattern for a variant; fields not bound are covered by `..`. */
const rustPattern = (c: WireCode, bindEnum: boolean, bindNumber: boolean): string => {
  if (c.enumField === undefined && c.numberField === undefined) return `Self::${c.variant}(detail)`;
  const bound = [
    ...(c.enumField !== undefined && bindEnum ? [snake(c.enumField)] : []),
    ...(c.numberField !== undefined && bindNumber ? [snake(c.numberField)] : []),
  ];
  const total = Number(c.enumField !== undefined) + Number(c.numberField !== undefined);
  return `Self::${c.variant} { ${[...bound, ...(bound.length < total ? ['..'] : [])].join(', ')} }`;
};

const rustSamples = (c: WireCode): string[] => {
  const num = c.numberField === undefined ? [] : [`${snake(c.numberField)}: ${String(SAMPLE_NUMBER)}`];
  if (c.enumField === undefined && c.numberField === undefined) {
    return (c.values ?? []).map((v) => `Self::${c.variant}(${c.valueType}::${pascal(v)})`);
  }
  const variants = c.enumField === undefined ? [undefined] : (c.values ?? []);
  return variants.map((v) =>
    rustBraces(
      `Self::${c.variant}`,
      [
        ...(v === undefined || c.enumField === undefined
          ? []
          : [`${snake(c.enumField)}: ${c.valueType}::${pascal(v)}`]),
        ...num,
      ],
      8,
      RUST_LITERAL_WIDTH,
    ),
  );
};

const generateRust = (spec: Spec): string => {
  const codes = wireCodes(spec);
  const enums = codes.flatMap((c) => (c.values ? [rustEnum(c.valueType, c.values, pascal)] : []));
  const arm = (c: WireCode, body: string, bindEnum: boolean, bindNumber: boolean): string =>
    `            ${rustPattern(c, bindEnum, bindNumber)} => ${body},`;
  const toWire = codes.map((c) => {
    const detail =
      c.enumField === undefined
        ? c.numberField === undefined
          ? 'detail.to_wire()'
          : '0'
        : `${snake(c.enumField)}.to_wire()`;
    return arm(
      c,
      `(pack(${String(c.id)}, ${detail}), ${c.numberField === undefined ? '0' : snake(c.numberField)})`,
      true,
      true,
    );
  });
  const fromWire = codes.map((c) => {
    const decode = `${c.valueType}::from_wire(detail)`;
    if (c.enumField === undefined && c.numberField === undefined)
      return `            ${String(c.id)} => ${decode}.map(Self::${c.variant}),`;
    const num = c.numberField === undefined ? [] : [`${snake(c.numberField)}: arg`];
    if (c.enumField === undefined)
      return `            ${String(c.id)} => (detail == 0).then_some(Self::${c.variant} { ${num.join(', ')} }),`;
    const parts = [snake(c.enumField), ...num];
    return `            ${String(c.id)} => ${decode}.map(|${snake(c.enumField)}| Self::${c.variant} { ${parts.join(', ')} }),`;
  });
  const display = codes.map((c) => {
    if (c.values === undefined) return arm(c, `f.write_str("${c.code}")`, false, false);
    const value = c.enumField === undefined ? 'detail' : snake(c.enumField);
    return arm(c, `write!(f, "${c.code}/{}", ${value}.as_str())`, true, false);
  });
  const limits = Object.entries(spec.limits.h1);
  return `// ${HEADER}

${enums.join('\n')}${rustEnum('Method', spec.methods, variantOf)}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ErrorCode {
${codes.map(rustVariant).join('\n')}
}

const fn pack(code: u32, detail: u32) -> u32 {
    code | (detail << 8)
}

impl ErrorCode {
    pub const ALL_SAMPLES: &[Self] = &[
${codes
  .flatMap(rustSamples)
  .map((s) => `        ${s},`)
  .join('\n')}
    ];

    /// Wire word 1 is \`code_id | detail_id << 8\`; word 2 is the numeric field.
    #[must_use]
    pub fn to_wire(self) -> (u32, u32) {
        match self {
${toWire.join('\n')}
        }
    }

    #[must_use]
    pub fn from_wire(code: u32, arg: u32) -> Option<Self> {
        let detail = code >> 8;
        match code & 0xFF {
${fromWire.join('\n')}
            _ => None,
        }
    }
}

impl core::fmt::Display for ErrorCode {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
${display.join('\n')}
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct H1Limits {
${limits.map(([k]) => `    pub ${snake(k)}: usize,`).join('\n')}
}

pub const H1_LIMITS: H1Limits = H1Limits {
${limits.map(([k, v]) => `    ${snake(k)}: ${rustNumber(v)},`).join('\n')}
};
`;
};

/** Validates the spec and returns the TypeScript and Rust sources. */
export function generate(spec: Spec): { ts: string; rust: string } {
  validateSpec(spec);
  return { ts: generateTs(spec), rust: generateRust(spec) };
}

export type DriftResult = { ok: true } | { ok: false; file: string };

/** First generated file whose committed content differs, or `{ ok: true }`. */
export function checkDrift(
  files: readonly { path: string; content: string }[],
  readCommitted: (path: string) => string | undefined,
): DriftResult {
  const drifted = files.find((f) => readCommitted(f.path) !== f.content);
  return drifted === undefined ? { ok: true } : { ok: false, file: drifted.path };
}

/* v8 ignore start -- CLI wrapper, exercised by `pnpm specgen --check` in CI */
if (import.meta.main) {
  const spec = parseSpec(JSON.parse(readFileSync('policy/spec.json', 'utf8')));
  const { ts, rust } = generate(spec);
  const files = [
    { path: TS_OUT, content: ts },
    { path: RUST_OUT, content: rust },
  ];
  if (process.argv.includes('--check')) {
    const result = checkDrift(files, (p) => {
      try {
        return readFileSync(p, 'utf8');
      } catch {
        return undefined;
      }
    });
    if (!result.ok) console.error(`${result.file} is out of date; run pnpm specgen`);
    process.exitCode = result.ok ? 0 : 1;
  } else {
    for (const f of files) writeFileSync(f.path, f.content);
  }
}
